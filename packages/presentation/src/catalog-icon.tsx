export function CatalogIcon({ name }: { name: unknown }) {
  if (typeof name === "string" && Object.hasOwn(icons, name)) {
    const Icon = icons[name]!;
    // oxlint-disable-next-line jsx-a11y/prefer-tag-over-role -- Lucide renders an inline SVG.
    return <Icon role="img" aria-label={name} />;
  }
  if (typeof name === "object" && name && "svgPath" in name && typeof name.svgPath === "string")
    return (
      <svg width="24" height="24" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
        <path d={name.svgPath} />
      </svg>
    );
  return null;
}
