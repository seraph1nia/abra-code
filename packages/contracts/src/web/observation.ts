import type { WorkspaceSnapshot } from "./contracts.ts";
import type { DeliveryOutcome } from "../workflow/delivery-contracts.ts";
import type { Observation } from "./changes.ts";

function semanticOutcome(outcome: DeliveryOutcome) {
  const { observed_at: _observed, finishing, ...evidence } = outcome;
  if (!finishing) return evidence;
  const { preflight_age_ms: _age, questions, ...details } = finishing;
  return {
    ...evidence,
    finishing: {
      ...details,
      questions: questions.map(({ age_ms: _age, ...question }) => question),
    },
  };
}

/** Strip only timestamps generated by this observation, never retained evidence times. */
export function semanticWorkspace(value: WorkspaceSnapshot) {
  const summary = <T extends { readonly observed_at: string }>(item: T) => {
    const { observed_at: _observed, ...rest } = item;
    return rest;
  };
  return {
    ...value,
    at: undefined,
    observation: undefined,
    work: {
      ...value.work,
      at: undefined,
      supervision: value.work.supervision
        ? {
            ...summary(value.work.supervision),
            tasks: value.work.supervision.tasks.map(summary),
          }
        : undefined,
      work: value.work.work.map((item) => ({
        ...item,
        outcome: item.outcome && semanticOutcome(item.outcome),
        supervision: item.supervision ? summary(item.supervision) : undefined,
      })),
    },
  };
}
export type ObservationDecision = "accept" | "duplicate" | "baseline_required";
/** Epoch changes require a baseline. Wall time is freshness, never ordering. */
export function observationDecision(
  current: Observation | undefined,
  next: Observation | undefined,
): ObservationDecision {
  if (!next) return current ? "baseline_required" : "accept";
  if (!current) return next.baseline ? "accept" : "baseline_required";
  if (current.epoch !== next.epoch) return next.baseline ? "accept" : "baseline_required";
  if (next.sequence <= current.sequence) return "duplicate";
  return next.baseline || next.sequence === current.sequence + 1 ? "accept" : "baseline_required";
}
